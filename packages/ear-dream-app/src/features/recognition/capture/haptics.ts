/**
 * 캡처 시작/종료 햅틱 피드백 — 플랫폼 중립 계약 + 네이티브(기본) 구현.
 *
 * ## 왜 필요한가
 *
 * 사용자는 한 손으로 폰을 들고 반대 손으로 수어를 한다. 시선은 자기 손과 프레이밍에
 * 가 있어서 **화면의 「녹화 중」 배지를 보지 못한다** — 지금 기록 중인지, 버튼을 제대로
 * 눌렀는지, 뗀 것이 반영됐는지가 화면을 봐야만 확인된다. 진동이 그 확인을 화면 밖으로
 * 꺼내 준다.
 *
 * ## 계약 1 — 시작과 종료는 「횟수」로 구분한다 (길이·세기가 아니라)
 *
 * **시작 = 1회, 종료 = 2회.**
 *
 * 길이로 나누지 않은 이유는 iOS 경로 때문이다(haptics.web.ts). iOS 웹에는 진동 API 가
 * 없고 유일한 우회가 "시스템 탭 1회"뿐이라 길이·세기를 전혀 제어할 수 없다. 횟수를
 * 기준으로 두면 안드로이드와 iOS 가 **같은 규약**을 공유한다 — 사용자가 기기를 바꿔도
 * 배운 것이 그대로 통한다.
 *
 * 이전 구현(시작 20ms / 종료 10ms)이 이 계약을 못 지켰다: 두 값 모두 다수 안드로이드
 * 기기의 지각 임계 아래이고, 설령 느껴져도 20ms 와 10ms 를 사람이 구분하지 못한다.
 * "녹화 중인지 알 수 없다"는 원래 문제가 진동을 켠 뒤에도 그대로였던 이유다.
 *
 * ## 계약 2 — 진동은 언제나 보조다
 *
 * 화면의 녹화 배지·버튼 상태 변화가 항상 병행된다. 진동이 없는 환경(데스크톱, 미지원
 * 브라우저, 시스템 진동 끔)에서도 기능은 완전하다. 그래서 이 모듈의 모든 함수는
 * **실패를 알리지 않고 조용히 no-op** 한다 — 호출 측이 분기할 것이 없다.
 *
 * ⚠️ `expo-haptics` 는 의존성에 없다. 모바일을 네이티브가 아니라 **모바일 웹**으로 가기로
 * 한 결정(CLAUDE.md)의 결과이지, 빠뜨린 것이 아니다. 네이티브 빌드가 필요해지면 팀 결정
 * 후 `npx expo install expo-haptics` 로 설치하고 이 파일만 교체하면 된다 — 계약(1회/2회)은
 * 그대로 두고 `Haptics.impactAsync` 로 갈아끼우면 된다.
 */

