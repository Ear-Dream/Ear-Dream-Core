/**
 * 캡처 시작 햅틱 피드백 — 플랫폼 중립 계약 + 네이티브(기본) 구현.
 *
 * ## 왜 필요한가
 *
 * 사용자는 한 손으로 폰을 들고 반대 손으로 수어를 한다. 시선은 자기 손과 프레이밍에 가
 * 있어서 **화면의 「녹화 중」 배지를 보지 못한다** — 버튼을 제대로 눌렀는지, 지금 기록이
 * 돌고 있는지가 화면을 봐야만 확인된다. 진동이 그 확인을 화면 밖으로 꺼내 준다.
 *
 * ## 계약 — 신호는 「시작」 하나뿐이다
 *
 * 처음에는 시작 1회 / 종료 2회 / 단어 확정 1회, 세 신호를 횟수로 구분했다. **실기기에서
 * 진동이 됐다 안 됐다 하는 문제로 되돌렸다**(2026-08-26). 원인은 안 울리는 것이 아니라
 * 신호끼리 서로를 잘라 먹는 것이었다:
 *
 * - Vibration API 는 새 호출이 재생 중인 진동을 취소하고 **대체**한다(스펙). 안드로이드
 *   일부는 대체가 아니라 **무시**한다는 보고도 있다 — 어느 쪽이든 신호 하나가 사라진다.
 * - 종료 2회는 520ms 를 점유했다. 단어 간격이 0.5초 안쪽이면 다음 단어의 시작 진동이
 *   앞 단어의 종료 진동을 매번 잘랐다.
 * - 단어 확정은 **서버 응답 시점**이라 언제 올지 모른다. 캡처 진동을 자르지 않게 미루면,
 *   이번엔 다음 동작에 밀려 대부분 버려졌다.
 *
 * 미루기·버리기 규칙을 얹어 봤지만 그것은 겹침을 **관리**하는 것이지 없애는 것이 아니었다.
 * 신호가 하나면 겹칠 대상이 없다 — 시작끼리는 사이에 「누르고 있는 시간 + 단어 간격」이
 * 통째로 들어가서 절대 겹치지 않는다. 그래서 불규칙성이 구조적으로 사라진다.
 *
 * 무엇을 잃었는지도 적어 둔다(되돌릴 때 근거가 된다):
 *
 * - **종료 진동** — 손실이 작다. 불확실한 쪽은 누를 때다("내 press 가 먹혔나"). 뗄 때는
 *   손가락이 떨어지는 것을 본인이 알아서 진동이 보탤 정보가 적다.
 * - **단어 확정 진동** — 어차피 대부분 버려지고 있었다. **불규칙한 신호는 없는 것보다
 *   나쁘다** — 신뢰를 학습할 수 없어 결국 화면을 보게 된다.
 *
 * ## 진동은 언제나 보조다
 *
 * 화면의 녹화 배지·버튼 상태 변화가 항상 병행된다. 진동이 없는 환경(데스크톱, 미지원
 * 브라우저, 시스템 진동 끔)에서도 기능은 완전하다. 그래서 이 모듈의 함수는 **실패를 알리지
 * 않고 조용히 no-op** 한다 — 호출 측이 분기할 것이 없다.
 *
 * ⚠️ `expo-haptics` 는 의존성에 없다. 모바일을 네이티브가 아니라 **모바일 웹**으로 가기로
 * 한 결정(CLAUDE.md)의 결과이지 빠뜨린 것이 아니다. 네이티브 빌드가 필요해지면 이 파일만
 * 교체하면 된다.
 */

/** 기록 시작 — 진동 1회. 이 모듈의 유일한 신호다(위 「계약」). */
export function captureStartFeedback(): void {
  // 네이티브에는 진동 수단이 없다(위 ⚠️). 시각 피드백만으로 동작한다.
}

/**
 * 실기기 진단용 스냅샷 — 개발 화면(`?dev=1`)의 햅틱 패널이 읽는다.
 *
 * 왜 필요한가: 진동이 안 오는 이유는 코드·번들·브라우저·기기 설정 어디에나 있을 수 있는데,
 * 폰에서는 콘솔을 열 수 없어 어느 층에서 끊겼는지 볼 방법이 없었다. `pulseMs` 를 함께 싣는
 * 것은 **지금 폰에서 도는 번들이 어느 버전인지**를 화면으로 증명하기 위해서다 — "빌드가
 * 반영됐나"를 추측으로 답하지 않게 한다.
 */
export interface HapticDiagnostics {
  /** 실제로 타는 경로. `none` 이면 이 브라우저에는 진동 수단이 없다. */
  path: 'vibration' | 'ios-switch' | 'none';
  vibrateAvailable: boolean;
  switchSupported: boolean;
  /**
   * 마지막 `navigator.vibrate()` 반환값. `false` 면 **브라우저가 거부**한 것이다(사용자
   * 제스처 없음 등). `true` 인데 안 느껴지면 브라우저는 요청을 받아들였다는 뜻이라 원인이
   * 기기 쪽(무음·방해금지·시스템 진동 끔·모터)에 있다 — 이 한 칸이 그 둘을 가른다.
   */
  lastVibrateResult: boolean | null;
  documentVisible: boolean;
  /** 지금 도는 번들의 진동 길이. 소스와 다르면 폰이 낡은 번들을 쓰고 있다는 뜻이다. */
  pulseMs: number;
  counters: {
    /** vibrate() 를 실제로 호출한 횟수. */
    emitted: number;
    /**
     * 앞 신호가 아직 재생 중인데 새 신호가 덮어쓴 횟수.
     *
     * **신호가 하나뿐인 지금 이 값은 항상 0 이어야 한다**(위 「계약」). 0 이 아니면 겹침이
     * 돌아왔다는 뜻이고, 불규칙성도 함께 돌아온다 — 회귀 감지용으로 남겨 둔 칸이다.
     */
    replaced: number;
  };
  userAgent: string;
}

/** 네이티브에는 진동 수단이 없다 — 경로 `none` 으로 보고한다. */
export function readHapticDiagnostics(): HapticDiagnostics {
  return {
    path: 'none',
    vibrateAvailable: false,
    switchSupported: false,
    lastVibrateResult: null,
    documentVisible: true,
    pulseMs: 0,
    counters: { emitted: 0, replaced: 0 },
    userAgent: '',
  };
}
