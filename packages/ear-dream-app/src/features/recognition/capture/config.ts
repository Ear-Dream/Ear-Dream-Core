/**
 * 세그먼트 캡처(T-23) 설정값.
 *
 * 여기 있는 시간값은 전부 **미확정 임시값**이다. 단어 경계를 어떻게 자를지(수동/정지 감지/고정
 * 길이) 자체가 미확정이고, 지금 구현은 그중 수동(버튼 누르는 동안) 방식의 프로토타입이다.
 * 사용자 검증·실측 전까지 확정값처럼 취급하지 말 것.
 */

/**
 * 프리롤(ms): 버튼을 누르기 **전**의 프레임을 얼마나 세그먼트에 포함할지.
 *
 * 엄지로 버튼을 누르는 동작과 수어 시작이 정확히 동시일 수 없어서, 누르기 직전 프레임을
 * 링 버퍼로 들고 있다가 함께 보낸다. 500ms 는 임시값이다 — 실제 사용자가 버튼을 누르고
 * 동작을 시작하기까지의 지연은 실측 전이다. 서버 전처리가 어차피 앞뒤 정지 구간을
 * 트리밍하므로(PreprocessInfo), 짧게 잡아 동작 앞부분을 자르는 쪽이 더 위험하다.
 */
export const PRE_ROLL_MS = 500;

/**
 * 포스트롤(ms): 버튼을 뗀 **후**의 프레임을 얼마나 더 모을지.
 *
 * 동작 끝과 버튼 떼기가 동시가 아닐 수 있어 뗀 뒤에도 잠깐 더 모은다. 300ms 는 임시값이다.
 */
export const POST_ROLL_MS = 300;

/**
 * 포스트롤 수집의 벽시계 타임아웃 여유(ms).
 *
 * 포스트롤은 프레임 타임스탬프 기준으로 끝나지만, 카메라가 프레임을 더 주지 않으면(탭 백그라운드
 * 전환 등) 타임스탬프가 멈춰 Promise 가 영원히 안 끝난다. POST_ROLL_MS + 이 값이 지나면
 * 그때까지 모인 프레임으로 마감한다. 임시값.
 */
export const POST_ROLL_TIMEOUT_GRACE_MS = 500;

