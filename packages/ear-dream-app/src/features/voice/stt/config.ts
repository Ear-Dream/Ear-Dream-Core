/**
 * 음성 인식(STT) 타이밍 값.
 *
 * **전부 프로토타입 임시값이다 — 확정값이 아니다.** 실사용(데모장 소음 · 실기기) 관찰 전까지
 * 근거가 없다는 사실을 드러내려고 한 파일에 모아 두었다. `capture/config.ts` 와 같은 취지.
 */

/**
 * "아무 말도 잡히지 않음" 안전장치(ms). 이 시간 안에 중간 텍스트조차 한 번도 오지 않으면
 * 세션을 끝내고 빈 결과를 돌려준다 — 화면은 "다시 말씀해 주세요" 안내를 띄운다.
 *
 * 10초는 시안 주석("음성 인식 시간(10초 이내)로 인식하지 못하면 다시 해달라는 알림창")을
 * 옮긴 값이다. 원래 mock 타이머였지만 **실제 안전장치로 남겼다** — 브라우저마다 무음
 * 자동 종료 동작이 달라 `onend`·`onerror` 가 아예 오지 않는 경우가 있고, 그러면 화면이
 * "듣고 있어요" 상태로 영원히 멈춘다. 그 유일한 탈출구다.
 *
 * ⚠️ 한 번이라도 말이 잡히면 이 타이머는 해제된다. 그 뒤로는 사용자가 정지를 누를 때까지
 * 기다린다 — 말하다 잠깐 쉰 것을 "인식 실패"로 처리해 애써 말한 문장을 버리면 안 된다.
 */
export const STT_NO_SPEECH_TIMEOUT_MS = 10_000;

/**
 * 엔진이 스스로 끝냈을 때 다시 열어 보는 횟수 상한.
 *
 * 브라우저는 `continuous = true` 를 줘도 무음이 이어지면 인식을 스스로 끝낸다(끝내는 시점은
 * 브라우저·버전마다 다르다). 사용자는 정지를 누르지 않았는데 조용히 멈추는 그 상황을 메우려고
 * 다시 연다. 말이 잡히면 0으로 되돌린다.
 *
 * 상한을 두는 이유는 폭주 방지다 — 엔진이 열자마자 끝나는 환경(마이크를 다른 앱이 잡고 있는
 * 경우 등)에서 무한 재시작이 되면 안 된다. 상한에 닿으면 그때까지 인식한 것으로 세션을 끝낸다.
 */
export const STT_MAX_AUTO_RESTARTS = 5;

/**
 * 정지를 누른 뒤 엔진의 종료 통지를 기다리는 상한(ms).
 *
 * 정상적으로는 `stop()` 직후 `onend` 가 온다. 오지 않는 브라우저를 만나면 화면이 '결과 확정
 * 중'에서 멈추므로, 이 시간이 지나면 그때까지 확정된 텍스트로 세션을 끝낸다.
 */
export const STT_FINALIZE_TIMEOUT_MS = 1500;
