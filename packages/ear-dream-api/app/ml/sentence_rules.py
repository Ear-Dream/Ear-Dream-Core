def compose(word_ids: list[str]) -> tuple[str, str]:
    """어휘 ID 열 → (문장, source). source ∈ {"template", "word_list"}.

    word_ids 는 호출 전에 어휘 검증을 마쳤다고 가정한다 (라우트에서 422 처리).
    """
    if len(word_ids) == 1:
        text = _SINGLE.get(word_ids[0])
        if text is not None:
            return text, "template"
    else:
        text = _MULTI.get(tuple(word_ids))
        if text is not None:
            return text, "template"

    # fallback: 문장을 지어내지 않고 라벨을 공백 연결
    labels = [ID_TO_ENTRY[wid].label for wid in word_ids]
    return " ".join(labels), "word_list"
